import { Injectable, Logger } from '@nestjs/common';
import { Skill, SkillInput, SkillOutput } from '../interfaces/skill.interface';
import { AIGatewayService } from '../../ai-gateway/ai-gateway.service';

@Injectable()
export class AssetRepairSkill implements Skill {
  readonly name = 'AssetRepair';
  private readonly logger = new Logger(AssetRepairSkill.name);

  constructor(private readonly aiGateway: AIGatewayService) {}

  async execute(input: SkillInput): Promise<SkillOutput> {
    const { originalPrompt, critique } = input.context;

    if (!originalPrompt || !critique) {
      throw new Error('AssetRepairSkill requires originalPrompt and critique in context.');
    }

    const systemPrompt = `You are an expert AI Image Prompt Engineer.
Your task is to fix a broken image generation prompt based on a visual critique.
The image generated by the original prompt failed Quality Assurance.

Critique / Reason for Failure:
${critique}

Original Prompt:
${originalPrompt}

Provide ONLY the updated, improved prompt. 
Ensure the new prompt explicitly avoids the issues mentioned in the critique.
Do not wrap it in quotes or markdown. Just the raw text of the new prompt.`;

    const response = await this.aiGateway.generateText('anthropic/claude-fable-5', {
      systemPrompt,
      messages: [{ role: 'user', content: 'Rewrite the prompt to fix the issues.' }],
      temperature: 0.7,
      maxTokens: 8192
    });

    const fixedPrompt = response.text.trim();
    this.logger.log(`Rewrote broken prompt. New prompt: ${fixedPrompt.substring(0, 50)}...`);

    return {
      hash: 'asset-repair-' + Date.now(),
      model: 'anthropic/claude-fable-5',
      usage: response.usage,
      data: { fixedPrompt }
    };
  }
}
