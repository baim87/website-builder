export function buildAssetRepairPrompt(originalPrompt: string, critique: string): string {
  return `You are an expert AI Image Prompt Engineer.
Your task is to fix a broken image generation prompt based on a visual critique.
The image generated by the original prompt failed Quality Assurance.

Critique / Reason for Failure:
${critique}

Original Prompt:
${originalPrompt}

Provide ONLY the updated, improved prompt. 
Ensure the new prompt explicitly avoids the issues mentioned in the critique.
Do not wrap it in quotes or markdown. Just the raw text of the new prompt.`;
}
